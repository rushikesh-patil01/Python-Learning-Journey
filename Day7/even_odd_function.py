# WAP to Check Even or Odd using Function

def check (num):
    if num % 2 == 0:
        print("Even")
    else:
        print("Odd")
        
check(10)


# WAP to Check user input number Even or Odd using Function

num = int(input("Enter a number:"))

def check(num):
    if num % 2 == 0:
        print("Even number")
    else:
        print("Odd number")
        
check(num)