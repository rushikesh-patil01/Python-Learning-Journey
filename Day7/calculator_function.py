# WAP to Create a Simple Calculator using Functions

def add(a,b):
    return a + b

def sub(a,b):
    return a - b

def multi(a, b):
    return a * b

def div(a, b):
    return a / b


print("Addition =", add(10, 5))
print("Subtraction =", sub(10, 5))
print("Multiplication =", multi(10, 5))
print("Division =", add(10, 5))