# Q] What is an F-string?
# -> A clean way to write strings that include variables.

name = "Himanshu" # name is of type str
age = 22          # age is now of type int
print(f"My name is {name} and I am {age} years old.")

# Output:
# My name is Rushikesh and I am 22 years old.
# Easier than using + or .format() — more readable!