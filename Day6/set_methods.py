# WAP to Add Elements in a Set

numbers = {10, 20, 30}
numbers.add(40)
print(numbers)

# remove
numbers = {10, 20, 30}
numbers.remove(20)
print(numbers)

# discard
numbers = {10, 20, 30}
numbers.discard(10)
print(numbers)

# pop
numbers = {10, 20, 30}
numbers.pop()
print(numbers)

# clear
numbers = {10, 20, 30}
numbers.clear()
print(numbers)
