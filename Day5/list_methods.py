# WAP to Add an Element using append()
list = [10, 20, 30]
print(list.append(40))
print(list)

# WAP to Insert an Element at a Specific Position
list.insert(1,100)
print(list)

# WAP to Remove an Element using remove()
list.remove(20)
print(list)

# WAP to Remove an Element using pop()
list.pop(1)
print(list)

# WAP to Update a List Element
list[0] = 200
print(list)

# WAP to sort a List Element
list.sort()
print(list)

# WAP to reverse a List Element
list.reverse()
print(list)

# WAP to count a List Element
print(list.count(20))

# WAP to index a List Element
list1 = [20, 40, 60, 80, 100]
print(list1.index(20))
