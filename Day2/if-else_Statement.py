# WAP to check number is Even or Odd.
num = int(input("Enter Number :"))
if num % 2 == 0:
    print("Even")
else:
    print("Odd")
    
# WAP Check if a person is an adult age > 18.
age = int(input("Enter your age :"))
if age >= 18:
    print("Adult")
else:
    print("Not an Adult")
    
# WAP Determine if a number is positive or negative.
num = int(input("Enter a Number :"))
if num > 0:
    print("Positive Number")
else:
    print("Negative Number")

# WAP Check if a temperature is cold or hot.
