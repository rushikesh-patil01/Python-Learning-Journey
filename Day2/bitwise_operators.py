# 7- Bitwise Operators      (&,|,~,^,<<,>>)

# 1- & (Bitwise and)
a=10
b=2
print(10 & 2)

'''
10 = 1010
2  = 0010  &  (1&1=1 else 0)
--------------
     0010
'''

print(7 & 3)
'''
111
011 &
------
011 = 3
'''

#2- | (Bitwise OR)
print(10 | 2)
'''
10 = 1010
2  = 0010  |  (0|0=0 ; else 1)
-------------
     1010 = 10
'''

#3- ~(Bitwise not)
a=-5
print(~a)
'''
~a
=-(a+1)
'''

#4- ^(EXOR)
a=10
b=5
print(10 ^ 6)
'''
10 = 1010
6  = 0110  ^ (0^0=0 ; 1^1=0  else 1)
-------------
     1100 = 12   
'''

#5- <<(Left Shift)
a=2
print(a<<2)

a=5
print(a<<3)
'''
2= 10
<<2 = 1000 = 8

5= 101
<<3 = 101000 =40
'''

#6- >>(Right Shift)
a=8
print(a>>2)
'''
8= 1000
>>2= 10 =2
'''
