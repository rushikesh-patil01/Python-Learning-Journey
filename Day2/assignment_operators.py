'''
2- Assignments Operators (=,+=,-=,*=,/=,%=,//=,**=)
    use to assign values or update the changes in data
'''
#1- Assignment (=)
a=5  # 5 is assigned to a
print('a:',a)

#2- Plus equal to(+=)
a=5
a+=3    # a=a+3 = 5+3 = 8
print('a+=3:',a)

#3- Minus equal to(-=)
a=5
a-=3    # a=a-3 = 5-3 = 2
print('a-=3:',a)

#4- Mutliplication equal to(*=)
a=5
a*=3    # a=a*3 = 5*3 = 15
print('a*=3:',a)

#5- Division equal to(/=)
a=5
a/=3    # a=a/3 = 5/3 = 1.666666666667
print('a/=3:',a)

#6- Mode equal to(%=)
a=5
a%=3    # a=a%3 = 5%3 = 2
print('a%=3:',a)

#7- Floor division equal to(//=)
a=5
a//=3    # a=a//3 = 5//3 = 1
print('a//=3:',a)

#8- Exponenetial equal to(**=)
a=5
a**=3    # a=a**3 = 5**3 = 125
print('a**=3:',a)
