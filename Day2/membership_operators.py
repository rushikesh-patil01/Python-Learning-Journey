'''
5- Membership Operators  (in , not in)
    Use to check the data is present in a datatype 
'''
# in =

l=[1,2,3,4]
a=5
print(a  in l)

s="I am in Pune"
sub="Pune"
sub1="Mumbai"
print(sub in s)
print(sub1 in s)

'''
IN
True:If content is present in a datatype 
else False
'''
print(sub1 not in s)
print(sub not in s)

'''
Not In:
True:If content is not present in a datatype 
else False
'''

